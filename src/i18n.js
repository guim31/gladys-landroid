/**
 * The result of the "Check the connection" action.
 * @param {{ mowers: { name: string, online: boolean }[], realtime: boolean, commandsLeft: number }} r
 */
export function checkReport({ mowers, realtime, commandsLeft }) {
  const names = mowers.map((m) => m.name).join(', ');
  const online = mowers.filter((m) => m.online).length;
  return {
    en: `${mowers.length} mower(s), ${online} online: ${names}. Real-time link: ${realtime ? 'up' : 'down'}. Commands left today: ${commandsLeft}.`,
    fr: `${mowers.length} tondeuse(s), ${online} en ligne : ${names}. Liaison temps réel : ${realtime ? 'active' : 'coupée'}. Commandes restantes aujourd'hui : ${commandsLeft}.`,
    de: `${mowers.length} Mähroboter, ${online} online: ${names}. Echtzeitverbindung: ${realtime ? 'aktiv' : 'getrennt'}. Verbleibende Befehle heute: ${commandsLeft}.`,
    es: `${mowers.length} robot(s), ${online} conectado(s): ${names}. Enlace en tiempo real: ${realtime ? 'activo' : 'caído'}. Órdenes restantes hoy: ${commandsLeft}.`,
  };
}

